#!/usr/bin/env python3
"""Generate src/promoview.css: dark-theme overrides for the Promoview brand.

Reads src/styles.css and, for every rule that hard-codes a light background, a white border
or a dark text colour, emits the same selector scoped to [data-brand=promoview] with the
dark-theme token instead. Re-run after changing styles.css:  python3 scripts/gen-promoview-theme.py
"""
import re, colorsys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
css = (root / 'src/styles.css').read_text()
css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
P = '[data-brand=promoview]'

def lum(h):
    h = h.lstrip('#')
    if len(h) == 3: h = ''.join(c * 2 for c in h)
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return colorsys.rgb_to_hls(r, g, b)[1]

HEX = r'#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b'

def fix_decls(body):
    out, keeps_light_bg = [], False
    decls = [d.strip() for d in body.split(';') if ':' in d]
    for d in decls:
        prop, val = d.split(':', 1); prop, val = prop.strip(), val.strip()
        if prop in ('background', 'background-color'):
            if 'var(--accent)' in val or 'var(--ink)' in val: continue
            hexes = re.findall(HEX, val)
            white_rgba = re.search(r'rgba\(255, ?255, ?255, ?([\d.]+)\)', val)
            if 'gradient' in val:
                if hexes and all(lum(h) > 0.84 for h in hexes) or (not hexes and white_rgba) or (hexes and white_rgba and all(lum(h) > 0.84 for h in hexes)):
                    out.append(f'{prop}: var(--surface-2)')
                elif 'rgba(240, 235, 255' in val or 'rgba(255, 255, 255, 0.9' in val:
                    out.append(f'{prop}: var(--surface-2)')
            elif white_rgba:
                out.append(f'{prop}: ' + ('var(--surface)' if float(white_rgba.group(1)) >= 0.6 else 'rgba(255, 255, 255, 0.04)'))
            elif hexes and len(hexes) == 1 and val == hexes[0]:
                if lum(hexes[0]) > 0.88: out.append(f'{prop}: var(--surface-2)' if lum(hexes[0]) < 0.99 else f'{prop}: var(--surface)')
                elif lum(hexes[0]) > 0.6: keeps_light_bg = True
            elif re.search(r'rgba\(239, ?235, ?255', val):
                out.append(f'{prop}: var(--accent-soft)')
        elif prop.startswith('border') and prop not in ('border-radius',) and 'radius' not in prop:
            if re.search(r'(#fff\b|#ffffff\b|rgba\(255, ?255, ?255, ?0\.[5-9]\d*\))', val, re.I):
                new = re.sub(r'#fff\b|#ffffff\b|rgba\(255, ?255, ?255, ?0\.[5-9]\d*\)', 'var(--line)', val, flags=re.I)
                out.append(f'{prop}: {new}')
        elif prop == 'color':
            m = re.fullmatch(HEX, val)
            if m and lum(val) < 0.36: out.append(('color', val))
    final = []
    for o in out:
        if isinstance(o, tuple):
            if not keeps_light_bg: final.append('color: var(--ink)')
        else: final.append(o)
    return final

def scope(sel):
    parts = []
    for s in sel.split(','):
        s = s.strip()
        if not s or s.startswith('@') or s in ('from', 'to') or s.endswith('%'): return None
        if s.startswith(':root') or s in ('html', 'body'): parts.append(s.replace(':root', f':root{P}') if s.startswith(':root') else f'{P} {s}' if s == 'body' else f'html{P}')
        elif s.startswith('[data-brand'): return None
        else: parts.append(f'{P} {s}')
    return ', '.join(parts)

def rules(block):
    res = []
    for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', block):
        sel, body = m.group(1).strip(), m.group(2)
        d = fix_decls(body); s = scope(sel)
        if d and s: res.append(f'{s} {{ {"; ".join(d)}; }}')
    return res

out = ['/* GENERATED by scripts/gen-promoview-theme.py. Do not edit by hand. */']
pos = 0
for m in re.finditer(r'@media[^{]+\{', css):
    out += rules(css[pos:m.start()])
    depth, i = 1, m.end()
    while depth and i < len(css):
        depth += {'{': 1, '}': -1}.get(css[i], 0); i += 1
    inner = rules(css[m.end():i - 1])
    if inner: out.append(m.group(0) + '\n  ' + '\n  '.join(inner) + '\n}')
    pos = i
out += rules(css[pos:])
(root / 'src/promoview.css').write_text('\n'.join(out) + '\n')
print(len(out), 'override rules')
